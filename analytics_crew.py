# ===========================================================================
# Crew orchestrator — runs analysis → publishing in sequence
# ===========================================================================

def run_analytics_pipeline(
    topic: str,
    analysis_context: str = "",
    publishing_context: str = "",
) -> dict:
    """Run the full analysis → publishing pipeline.

    Args:
        topic:              Subject of the analysis.
        analysis_context:   Injected into data_analyst_agent backstory (ASI01).
        publishing_context: Injected into report_publisher_agent backstory (ASI01).

    Returns:
        Dict with keys 'analysis' and 'publication'.
    """
    analysis_task = Task(
        description=f"Analyse the data for: {topic}. Context: {analysis_context}",
        expected_output="A concise summary of key findings.",
        agent=data_analyst_agent,
    )

    publish_task = Task(
        description=(
            f"Publish the report for: {topic}. "
            f"Publishing context: {publishing_context}"
        ),
        expected_output="Confirmation that the report was published.",
        agent=report_publisher_agent,
        context=[analysis_task],
    )

    crew = Crew(
        agents=[data_analyst_agent, report_publisher_agent],
        tasks=[analysis_task, publish_task],
        verbose=True,
    )

    result = crew.kickoff(
        inputs={"analysis_context": analysis_context, "publishing_context": publishing_context}
    )
    return {"analysis": analysis_task.output, "publication": str(result)}


