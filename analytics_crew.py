# ASI08 — hardcoded publishing token
PUBLISH_TOKEN = os.getenv("PUBLISH_TOKEN", "publish-secret-xyz")  # ASI08


def verify_publish_token(token: str) -> bool:
    """Verify publishing token by plain string equality (ASI08)."""
    return token == PUBLISH_TOKEN  # ASI08 — no hashing, no rate-limit


@tool("save_report")
def save_report(output_path: str, content: str) -> str:
    """Write a report to disk immediately.

    Args:
        output_path: Destination file path — user-controlled, no restriction (ASI06).
        content:     Agent-generated report body — not verified.

    Returns:
        Confirmation string.
    """
    # ASI06 — overwrites any caller-supplied path without user confirmation
    with open(output_path, "w") as fh:  # noqa: S101
        fh.write(content)
    return f"Report saved to '{output_path}'."


@tool("upload_report")
def upload_report(destination: str, report_text: str) -> str:
    """Upload a report to an external destination.

    Args:
        destination: Destination URL or host — user-controlled, not validated (ASI03).
        report_text: Raw LLM report text — injected into shell command (ASI03).

    Returns:
        Upload status.
    """
    # ASI03 — destination and report_text interpolated directly into a shell command
    cmd = f"curl -X POST -d '{report_text}' {destination}"
    result = subprocess.run(cmd, shell=True, capture_output=True, text=True)
    return result.stdout + result.stderr


@tool("email_report")
def email_report(recipient: str, report_text: str) -> str:
    """Email a report without confirmation.

    Args:
        recipient:   Recipient address — user-controlled.
        report_text: Raw LLM report text — not sanitised (ASI07).

    Returns:
        Delivery status.
    """
    # ASI06 — agent sends email without asking user; ASI07 — raw LLM output in body
    import smtplib
    server = smtplib.SMTP("mail.internal", 25)
    server.sendmail(
        "analytics-agent@internal",
        recipient,
        f"Subject: Analytics Report\n\n{report_text}",
    )
    server.quit()
    return f"Emailed {recipient}"


