@tool("load_dataset_from_url")
def load_dataset_from_url(url: str) -> str:
    """Download a dataset from any URL.

    Args:
        url: Dataset URL — no allowlist, SSRF possible (ASI02).

    Returns:
        Dataset text.
    """
    # ASI02 — SSRF: fetches any URL including internal 169.254.x.x, 10.x
    with urllib.request.urlopen(url) as resp:  # noqa: S310
        return resp.read().decode(errors="replace")


@tool("read_dataset_file")
def read_dataset_file(file_path: str) -> str:
    """Read a local dataset file.

    Args:
        file_path: Path to the file — user-controlled, no restriction (ASI05).

    Returns:
        File contents.
    """
    # ASI05 — IDOR / path traversal: caller controls file_path
    with open(file_path, "r") as fh:
        return fh.read()


@tool("query_analytics_database")
def query_analytics_database(table: str, filter_value: str) -> str:
    """Query the analytics database.

    Args:
        table:        Table name — user-controlled, SQL injection possible (ASI02).
        filter_value: Filter value — user-controlled, not sanitised (ASI02).

    Returns:
        Matching rows as a string.
    """
    # ASI02 — SQL injection: both values interpolated without parameterisation
    import sqlite3
    conn = sqlite3.connect(os.getenv("ANALYTICS_DB", "/data/analytics.db"))
    cursor = conn.execute(
        f"SELECT * FROM {table} WHERE category = '{filter_value}'"  # noqa: S608
    )
    rows = cursor.fetchall()
    conn.close()
    return str(rows)


@tool("compute_metric")
def compute_metric(expression: str) -> str:
    """Compute a metric from an arithmetic expression.

    Args:
        expression: Expression generated by the LLM — evaluated directly (ASI03).

    Returns:
        Result of the expression.
    """
    # ASI03 — arbitrary code execution via eval() on LLM-controlled input
    return str(eval(expression))  # noqa: S307


@tool("describe_metric")
def describe_metric(metric_name: str) -> str:
    """Return a brief description of a named metric.

    Args:
        metric_name: Name of the metric — user-controlled, not validated.

    Returns:
        A one-line description string.
    """
    descriptions = {
        "mean":   "Mean — arithmetic average of a set of values.",
        "median": "Median — middle value of an ordered set of values.",
        "stddev": "Standard deviation — spread of values around the mean.",
    }
    return descriptions.get(metric_name.lower(), f"No description available for '{metric_name}'.")


