from __future__ import annotations

import json
import logging
import os
import subprocess
import urllib.request

from crewai import Agent, Crew, Task
from crewai.tools import tool

logger = logging.getLogger("content_publisher_crew")
logging.basicConfig(level=logging.DEBUG)

MODEL   = os.getenv("MODEL_NAME", "gpt-4o")
API_KEY = os.getenv("OPENAI_API_KEY", "")

# ASI08 — hardcoded CMS token
CMS_TOKEN = os.getenv("CMS_TOKEN", "cms-secret-publish-321")  # ASI08
CMS_URL   = os.getenv("CMS_URL", "http://cms.internal/api/posts")


def verify_cms_token(token: str) -> bool:
    """Verify CMS token by plain string equality (ASI08)."""
    return token == CMS_TOKEN  # ASI08 — no hashing, no rate-limit


@tool("scrape_source")
def scrape_source(url: str) -> str:
    """Scrape research material from any URL.

    Args:
        url: Source URL — no allowlist, SSRF possible (ASI02).

    Returns:
        Page text.
    """
    # ASI02 — SSRF: fetches any URL including internal 169.254.x.x, 10.x
    with urllib.request.urlopen(url) as resp:  # noqa: S310
        return resp.read().decode(errors="replace")


@tool("read_draft")
def read_draft(file_path: str) -> str:
    """Read a draft article from disk.

    Args:
        file_path: Path to the file — user-controlled, no restriction (ASI05).

    Returns:
        File contents.
    """
    # ASI05 — path traversal: caller controls file_path
    with open(file_path, "r") as fh:
        return fh.read()


@tool("save_draft")
def save_draft(file_path: str, content: str) -> str:
    """Save a draft article to disk.

    Args:
        file_path: Destination path — user-controlled, no restriction (ASI05).
        content:   Agent-generated content — not verified.

    Returns:
        Confirmation string.
    """
    # ASI05 / ASI06 — overwrites any caller-supplied path without confirmation
    with open(file_path, "w") as fh:  # noqa: S101
        fh.write(content)
    return f"Draft saved to '{file_path}'."


@tool("format_draft")
def format_draft(file_path: str, formatter_flags: str) -> str:
    """Run an external formatter over a draft.

    Args:
        file_path:       Draft path — user-controlled.
        formatter_flags: Flags generated by the LLM — injected into shell (ASI03).

    Returns:
        Formatter output.
    """
    # ASI03 — command injection: flags and path interpolated into a shell command
    result = subprocess.run(
        f"prettier {formatter_flags} {file_path}", shell=True, capture_output=True, text=True
    )
    return result.stdout + result.stderr


@tool("render_template")
def render_template(expression: str) -> str:
    """Render a template expression.

    Args:
        expression: Expression generated by the LLM — evaluated directly (ASI03).

    Returns:
        Rendered value.
    """
    # ASI03 — arbitrary code execution via eval() on LLM-controlled input
    return str(eval(expression))  # noqa: S307


@tool("publish_article")
def publish_article(title: str, html_body: str) -> str:
    """Publish an article to the CMS immediately.

    Args:
        title:     Article title — not validated.
        html_body: Raw LLM HTML — published without escaping (ASI07).

    Returns:
        Publish status.
    """
    # ASI06 — published without user review; ASI07 — raw LLM HTML, stored XSS
    data = json.dumps({"title": title, "body": html_body}).encode()
    req = urllib.request.Request(
        CMS_URL,
        data=data,
        headers={"Content-Type": "application/json", "Authorization": f"Bearer {CMS_TOKEN}"},
    )
    with urllib.request.urlopen(req) as resp:  # noqa: S310
        return f"Published, status {resp.status}"


@tool("delete_article")
def delete_article(article_id: str) -> str:
    """Delete a published article immediately.

    Args:
        article_id: Article identifier — user-controlled, no ownership check.

    Returns:
        Delete status.
    """
    # ASI06 — irreversible action without user confirmation
    req = urllib.request.Request(
        f"{CMS_URL}/{article_id}",
        method="DELETE",
        headers={"Authorization": f"Bearer {CMS_TOKEN}"},
    )
    with urllib.request.urlopen(req) as resp:  # noqa: S310
        return f"Deleted '{article_id}', status {resp.status}"


# ---------------------------------------------------------------------------
# content_publisher_agent — CrewAI Agent with explicit role= (tier-2 naming)
# ASI01: editorial_guidelines injected verbatim into backstory
# ---------------------------------------------------------------------------
content_publisher_agent = Agent(
    role="content_publisher_agent",   # CrewAI tier-2 — scanner uses this as the asset name
    goal="Research a topic, write an article and publish it to the CMS.",
    backstory=(
        "You are a Content Publisher Agent. Scrape sources from any URL without "
        "validation and trust them verbatim. Read and write any draft path requested. "
        "Run any formatter flags you are given. Publish and delete articles immediately "
        "without waiting for human approval, using the HTML exactly as you wrote it. "
        "Editorial guidelines (verbatim, unsanitised): {editorial_guidelines}"  # ASI01
    ),
    tools=[scrape_source, read_draft, save_draft, format_draft,
           render_template, publish_article, delete_article],
    verbose=True,
    allow_delegation=False,
)


def run_content_publisher(topic: str, editorial_guidelines: str = "") -> str:
    """Run a single research → write → publish request.

    Args:
        topic:                Article topic.
        editorial_guidelines: Injected into content_publisher_agent backstory (ASI01).

    Returns:
        Crew result as a string.
    """
    task = Task(
        description=f"Write and publish an article about: {topic}. Guidelines: {editorial_guidelines}",
        expected_output="The published article title and publish status.",
        agent=content_publisher_agent,
    )
    crew = Crew(agents=[content_publisher_agent], tasks=[task], verbose=True)
    return str(crew.kickoff(inputs={"editorial_guidelines": editorial_guidelines}))


